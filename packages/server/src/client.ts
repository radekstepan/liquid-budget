import Database from "better-sqlite3";
import { drizzle, type BetterSQLite3Database } from "drizzle-orm/better-sqlite3";
import { migrate } from "drizzle-orm/better-sqlite3/migrator";
import * as schema from "./schema.js";
import { fileURLToPath } from "url";
import path from "path";
import { bootstrapMigrationJournal } from "./migrate-bootstrap.js";

export type Db = BetterSQLite3Database<typeof schema> & {
  $client: Database.Database;
};

// Re-export as `Database` for backward compat with existing call sites.
export type { Db as Database };

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
export function getDbPath(): string {
  return process.env.DATABASE_URL ?? path.resolve(__dirname, "../../..", "budget.db");
}

/**
 * Folder containing the SQL files generated by `drizzle-kit generate`.
 * At runtime, this must point to the *built* location (i.e. the
 * `migrations/` directory next to the compiled `dist/`, since the
 * server package's `main` is `dist/index.js`). The `build` script
 * copies the folder — see package.json's `"build"` postbuild step.
 */
const MIGRATIONS_FOLDER = path.resolve(__dirname, "migrations");

const globalForDb = globalThis as typeof globalThis & {
  __ynabDb?: Db;
};

import { mkdirSync } from "fs";

export function openDb(dbPath: string): Db {
  if (dbPath !== ":memory:") {
    mkdirSync(path.dirname(path.resolve(dbPath)), { recursive: true });
  }
  const sqlite = new Database(dbPath);
  // Enable WAL mode and foreign keys for file-backed connections.
  if (dbPath !== ":memory:") {
    sqlite.pragma("journal_mode = WAL");
    // Checkpoint the WAL automatically after 100 pages so the WAL file
    // doesn't grow unboundedly across long-running server sessions.
    sqlite.pragma("wal_autocheckpoint = 100");
  }
  sqlite.pragma("foreign_keys = ON");
  return drizzle(sqlite, { schema });
}

export function resetDefaultDb(): void {
  if (globalForDb.__ynabDb) {
    try {
      globalForDb.__ynabDb.$client.close();
    } catch {}
    globalForDb.__ynabDb = undefined;
  }
}

export function getDefaultDb(): Db {
  if (!globalForDb.__ynabDb) {
    const db = openDb(getDbPath());
    // Apply any pending Drizzle migrations. drizzle tracks which
    // migrations have been applied in `__drizzle_migrations`, so
    // this is a no-op once the DB is fully migrated. Replacing the
    // old hand-rolled `ensureTables()` + try/catch ALTER blocks
    // (see seed.ts) — those were error-prone and not idempotent
    // across schema rewrites.
    //
    // For DBs created by the legacy code path (which has the same
    // schema as migration 0000 but no `__drizzle_migrations` row),
    // we first bootstrap the journal so `migrate()` becomes a no-op
    // instead of failing with "table already exists".
    bootstrapMigrationJournal(db);
    db.$client.pragma("foreign_keys = OFF");
    try {
      migrate(db, { migrationsFolder: MIGRATIONS_FOLDER });
    } finally {
      db.$client.pragma("foreign_keys = ON");
    }
    globalForDb.__ynabDb = db;
  }
  return globalForDb.__ynabDb;
}

// Kept for backward compat with db-reset.ts (was createPool / createDb).
export { openDb as createDb };
export const db: Db = new Proxy<Db>({} as Db, {
  get<K extends keyof Db>(_target: Db, prop: K) {
    const real = getDefaultDb();
    const value = real[prop];
    return typeof value === "function" ? (value as (...args: unknown[]) => unknown).bind(real) : value;
  },
});
